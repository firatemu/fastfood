#!/usr/bin/env bash
# Signed Android release APK for the ADR-021 environment, run inside WSL.
#
#   scripts/android-build-release.sh customer-mobile
#   scripts/android-build-release.sh courier-mobile
#
# Required environment:
#   FASTFOOD_RELEASE_KEYSTORE        path to the release keystore (outside Git)
#   FASTFOOD_RELEASE_KEYSTORE_PASS   keystore + key password
#   FASTFOOD_RELEASE_KEY_ALIAS       key alias
# Optional:
#   EXPO_PUBLIC_API_BASE_URL         default https://apiburger.azem.cloud/api/v1
#
# Signing is injected through AGP's `android.injected.signing.*` properties so
# the Expo-generated build.gradle (git-ignored, regenerated by prebuild) stays
# untouched. local.properties is swapped to the Linux SDK and restored on exit,
# like scripts/android-build.sh.
set -uo pipefail

APP="${1:?usage: android-build-release.sh <customer-mobile|courier-mobile>}"
ROOT="/home/azem/projects/fastfood/apps/${APP}/android"
SDK="$HOME/Android/Sdk"
PROPS="${ROOT}/local.properties"
BACKUP="$(mktemp)"

: "${FASTFOOD_RELEASE_KEYSTORE:?set FASTFOOD_RELEASE_KEYSTORE}"
: "${FASTFOOD_RELEASE_KEYSTORE_PASS:?set FASTFOOD_RELEASE_KEYSTORE_PASS}"
: "${FASTFOOD_RELEASE_KEY_ALIAS:?set FASTFOOD_RELEASE_KEY_ALIAS}"
export EXPO_PUBLIC_API_BASE_URL="${EXPO_PUBLIC_API_BASE_URL:-https://apiburger.azem.cloud/api/v1}"

[ -d "$ROOT" ] || { echo "FAIL: no android project at $ROOT"; exit 1; }
[ -d "$SDK" ]  || { echo "FAIL: no Linux Android SDK at $SDK"; exit 1; }
[ -f "$FASTFOOD_RELEASE_KEYSTORE" ] || { echo "FAIL: keystore not found"; exit 1; }

restore() {
  if [ -f "$BACKUP" ]; then cp "$BACKUP" "$PROPS"; rm -f "$BACKUP"; fi
}
trap restore EXIT INT TERM

if [ -f "$PROPS" ]; then cp "$PROPS" "$BACKUP"; fi
printf 'sdk.dir=%s\n' "$SDK" > "$PROPS"

cd "$ROOT" || exit 1
chmod +x gradlew 2>/dev/null || true

echo "=== gradlew assembleRelease (${APP}) -> ${EXPO_PUBLIC_API_BASE_URL} ==="
export ANDROID_HOME="$SDK"
export ANDROID_SDK_ROOT="$SDK"
export NODE_ENV=production
./gradlew assembleRelease --console=plain --no-daemon \
  -Pandroid.injected.signing.store.file="$FASTFOOD_RELEASE_KEYSTORE" \
  -Pandroid.injected.signing.store.password="$FASTFOOD_RELEASE_KEYSTORE_PASS" \
  -Pandroid.injected.signing.key.alias="$FASTFOOD_RELEASE_KEY_ALIAS" \
  -Pandroid.injected.signing.key.password="$FASTFOOD_RELEASE_KEYSTORE_PASS"
status=$?

echo "=== exit code: ${status} ==="
if [ $status -eq 0 ]; then
  find "$ROOT/app/build/outputs/apk/release" -name "*.apk" 2>/dev/null
fi
exit $status
