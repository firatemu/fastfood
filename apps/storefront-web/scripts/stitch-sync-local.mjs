#!/usr/bin/env node
/* eslint-disable no-console, no-restricted-syntax */
/**
 * Sync manual Stitch export → `.stitch/export/<slug>/` + `public/stitch-raw/*.html`
 * Source: repo-root `stitch_burger_e_ticaret_platformu_tasarım/` (or STITCH_LOCAL_SRC).
 */
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { enrichStitchHtml } from './stitch-enrich-html.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const REPO = join(ROOT, '..', '..');
const DEFAULT_SRC = join(REPO, 'stitch_burger_e_ticaret_platformu_tasarım');
const EXPORT = join(ROOT, '.stitch', 'export');
const RAW = join(ROOT, 'public', 'stitch-raw');

/** Stitch folder name → canonical slug (storefront routes). */
const FOLDER_TO_SLUG = {
  ana_sayfa_canl_men_vitrini: 'home',
  kullan_c_giri_kay_t_ekran: 'auth',
  kullan_c_hesab_profil_y_netimi: 'account',
  kullan_c_hesab_canl_sipari_takibi: 'orders',
  zelle_tirilebilir_r_n_sepet_detay: 'pdp-cart',
  sipari_h_zl_deme_sayfas: 'checkout',
};

function valid(html) {
  if (!html || html.includes('accounts.google.com')) return false;
  return html.includes('<!DOCTYPE') || html.includes('<html');
}

function main() {
  const srcRoot = process.env.STITCH_LOCAL_SRC?.trim() || DEFAULT_SRC;
  if (!existsSync(srcRoot)) {
    console.error(`Source not found: ${srcRoot}`);
    process.exit(1);
  }

  mkdirSync(EXPORT, { recursive: true });
  mkdirSync(RAW, { recursive: true });

  const slugs = [];
  for (const [folder, slug] of Object.entries(FOLDER_TO_SLUG)) {
    const htmlPath = join(srcRoot, folder, 'code.html');
    if (!existsSync(htmlPath)) {
      console.error(`Missing ${htmlPath}`);
      process.exit(1);
    }
    const html = readFileSync(htmlPath, 'utf8');
    if (!valid(html)) {
      console.error(`Invalid HTML: ${folder}`);
      process.exit(1);
    }
    const outDir = join(EXPORT, slug);
    mkdirSync(outDir, { recursive: true });
    const enriched = enrichStitchHtml(html);
    writeFileSync(join(outDir, 'code.html'), enriched, 'utf8');
    writeFileSync(join(RAW, `${slug}.html`), enriched, 'utf8');
    const png = join(srcRoot, folder, 'screen.png');
    if (existsSync(png)) {
      copyFileSync(png, join(outDir, 'screen.png'));
    }
    console.log(`sync  ${folder} → ${slug} (${html.length} bytes)`);
    slugs.push(slug);
  }

  const designSrc = join(srcRoot, 'smash_co._gourmet_visual_system', 'DESIGN.md');
  if (existsSync(designSrc)) {
    copyFileSync(designSrc, join(ROOT, '.stitch', 'DESIGN.md'));
  }

  for (const name of readdirSafe(EXPORT)) {
    if (name.startsWith('.')) continue;
    if (!slugs.includes(name)) {
      rmSync(join(EXPORT, name), { recursive: true, force: true });
      console.log(`removed stale export/${name}`);
    }
  }

  writeFileSync(
    join(RAW, 'manifest.json'),
    `${JSON.stringify({ slugs, syncedAt: new Date().toISOString() }, null, 2)}\n`,
    'utf8',
  );

  const ts = `/** Generated by scripts/stitch-sync-local.mjs — do not edit. */
import type { StitchSlug } from './stitch-export';

export const STITCH_PUBLISHED_SLUGS: readonly StitchSlug[] = ${JSON.stringify(slugs)} as StitchSlug[];
`;
  writeFileSync(join(ROOT, 'src/stitch/stitch-published.ts'), ts, 'utf8');
  console.log('OK  stitch-published.ts + public/stitch-raw/manifest.json');
}

function readdirSafe(dir) {
  try {
    return readdirSync(dir);
  } catch {
    return [];
  }
}

main();
