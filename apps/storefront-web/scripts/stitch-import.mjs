#!/usr/bin/env node
/* eslint-disable no-console, no-restricted-syntax */
/**
 * Reads `.stitch/export/<slug>/code.html` and emits `src/stitch/generated/<slug>.tsx`.
 */
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import * as cheerio from 'cheerio';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const EXPORT_DIR = join(ROOT, '.stitch', 'export');
const OUT_DIR = join(ROOT, 'src', 'stitch', 'generated');
const PUBLIC_TW = join(ROOT, 'public', 'storefront', 'stitch', 'tailwind-config.js');

const SLUGS = ['home', 'auth', 'account', 'orders', 'pdp-cart', 'checkout'];

function escapeTemplateLiteral(value) {
  return value.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
}

function isValidStitchHtml(html) {
  if (!html || html.includes('accounts.google.com/v3/signin')) return false;
  return html.includes('<body') || html.includes('tailwindcss') || html.includes('tailwind.config');
}

function syncPublicTailwindConfig(html) {
  const marker = 'id="tailwind-config"';
  const idx = html.indexOf(marker);
  if (idx === -1) return;
  const open = html.indexOf('>', idx);
  const close = html.indexOf('</script>', open);
  if (open === -1 || close === -1) return;
  const body = html.slice(open + 1, close).trim();
  if (!body.includes('tailwind.config')) return;
  writeFileSync(PUBLIC_TW, `${body}\n`, 'utf8');
  console.log('Synced public/storefront/stitch/tailwind-config.js from export');
}

function normalizeBodyHtml($, body) {
  body.find('script').remove();
  body.find('style').remove();
  body.find('[data-stitch-slot]').each((_, el) => {
    const key = el.attribs['data-stitch-slot'];
    $(el).replaceWith(`<!-- stitch-slot:${key} -->`);
  });
  return body.html()?.trim() ?? '';
}

function splitSlots(rawHtml) {
  const slotNames = [];
  const re = /<!--\s*stitch-slot:([a-zA-Z0-9_-]+)\s*-->/g;
  let m;
  while ((m = re.exec(rawHtml)) !== null) {
    if (!slotNames.includes(m[1])) slotNames.push(m[1]);
  }
  const parts = rawHtml.split(/<!--\s*stitch-slot:[a-zA-Z0-9_-]+\s*-->/);
  const markers = [...rawHtml.matchAll(/<!--\s*stitch-slot:([a-zA-Z0-9_-]+)\s*-->/g)].map((x) => x[1]);
  return { parts, markers, slotNames };
}

function pascalCase(slug) {
  return slug
    .split(/[-_]/)
    .map((s) => s.charAt(0).toUpperCase() + s.slice(1))
    .join('');
}

function generateComponent(slug, rawHtml, slotNames) {
  const component = `Stitch${pascalCase(slug)}`;
  const { parts, markers } = splitSlots(rawHtml);
  const partLiterals = parts.map((p) => escapeTemplateLiteral(p));

  let bodyJsx = '';
  for (let i = 0; i < partLiterals.length; i += 1) {
    bodyJsx += `      <StitchHtmlFragment html={PARTS[${i}]} slotKey="${slug}-part-${i}" />\n`;
    if (i < markers.length) {
      const key = markers[i];
      bodyJsx += `      {slots?.[${JSON.stringify(key)}] ?? null}\n`;
    }
  }

  const slotsType =
    slotNames.length > 0
      ? `{ slots?: Partial<Record<${slotNames.map((s) => JSON.stringify(s)).join(' | ')}, ReactNode>> }`
      : '{ slots?: Record<string, ReactNode> }';

  return `'use client';
/* eslint-disable */
/** Auto-generated by scripts/stitch-import.mjs — do not edit manually. */
import type { ReactNode } from 'react';

import { StitchHtmlFragment } from '../StitchHtmlFragment';

const PARTS = [
${partLiterals.map((p) => `  \`${p}\`,`).join('\n')}
] as const;

export default function ${component}({ slots }: ${slotsType}) {
  return (
    <>
${bodyJsx}    </>
  );
}
`;
}

function writeIndex(slugs) {
  const exports = slugs
    .map((s) => `export { default as Stitch${pascalCase(s)} } from './${s}';`)
    .join('\n');
  writeFileSync(join(OUT_DIR, 'index.ts'), `${exports}\n`, 'utf8');
  writeFileSync(
    join(OUT_DIR, 'manifest.json'),
    `${JSON.stringify({ slugs, generatedAt: new Date().toISOString() }, null, 2)}\n`,
    'utf8',
  );
}

function main() {
  mkdirSync(OUT_DIR, { recursive: true });
  let discovered = [];
  try {
    discovered = readdirSync(EXPORT_DIR, { withFileTypes: true })
      .filter((d) => d.isDirectory())
      .map((d) => d.name)
      .filter((name) => SLUGS.includes(name));
  } catch {
    console.warn('No .stitch/export directory yet.');
    writeIndex([]);
    process.exit(0);
  }

  const ok = [];
  for (const slug of discovered) {
    const file = join(EXPORT_DIR, slug, 'code.html');
    let html;
    try {
      html = readFileSync(file, 'utf8');
    } catch {
      console.warn(`SKIP ${slug}: no code.html`);
      continue;
    }
    if (!isValidStitchHtml(html)) {
      console.warn(`SKIP ${slug}: invalid or sign-in interstitial HTML`);
      continue;
    }
    if (slug === 'home') syncPublicTailwindConfig(html);

    const $ = cheerio.load(html);
    const raw = normalizeBodyHtml($, $('body'));
    const { slotNames } = splitSlots(raw);
    const source = generateComponent(slug, raw, slotNames);
    writeFileSync(join(OUT_DIR, `${slug}.tsx`), source, 'utf8');
    console.log(`OK  ${slug}  (${raw.length} chars, slots: ${slotNames.join(', ') || 'none'})`);
    ok.push(slug);
  }

  writeIndex(ok);
  if (ok.length === 0) {
    console.warn('No components generated. Run stitch:pull first.');
  }
}

main();
